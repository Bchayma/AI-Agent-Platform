from agents.base_agent import BaseAgent
from datetime import datetime

SYSTEM_PROMPT = """You are a Report Agent specialized in generating formal, professional reports.
Your job is to:
1. Structure content as a formal business/technical report
2. Include all standard report sections
3. Use professional language
4. Highlight metrics, status, and actionable insights
5. Provide clear conclusions and next steps

Reports must be executive-ready — clear, factual, and decision-enabling."""

class ReportAgent(BaseAgent):
    def __init__(self):
        super().__init__(
            name="ReportAgent",
            role="Report Generator",
            goal="Create formal, professional reports from gathered information",
        )

    async def run(self, content: str, topic: str, sections: list[str] | None = None) -> str:
        self._log("start", f"Generating report: {topic}")

        default_sections = [
            "Executive Summary",
            "Background & Context",
            "Key Findings",
            "Analysis",
            "Risks & Issues",
            "Recommendations",
            "Next Steps",
            "Conclusion",
        ]
        use_sections = sections or default_sections
        sections_str = "\n".join(f"- {s}" for s in use_sections)
        now = datetime.utcnow().strftime("%B %d, %Y – %H:%M UTC")

        prompt = f"""Generate a formal professional report based on the following information.

REPORT TITLE: {topic}
DATE: {now}

REQUIRED SECTIONS:
{sections_str}

SOURCE INFORMATION:
{content}

Format requirements:
- Start with a clear report header (Title, Date, Prepared By: AI Agent Platform)
- Each section should have an H2 heading
- Use sub-bullets for details
- Include a status indicator where relevant (✅ Good / ⚠️ Warning / ❌ Critical)
- End with a signature block: "Generated by AI Agent Platform — Report Agent"
- Keep a professional, formal tone throughout"""

        result = await self.call_llm(prompt, SYSTEM_PROMPT)
        self._log("complete", "Report generated")
        return result
